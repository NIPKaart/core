import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import process from 'node:process';
import { fileURLToPath } from 'node:url';
import prettier from 'prettier';

const root = new URL('../resources/locales/', import.meta.url);
function catalogs(directory) {
    return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
        const file = new URL(entry.name + (entry.isDirectory() ? '/' : ''), directory);
        return entry.isDirectory() ? catalogs(file) : [file];
    });
}
const entries = catalogs(root)
    .filter((file) => /\/en\/.+\.json$/.test(file.pathname))
    .sort((a, b) => a.pathname.localeCompare(b.pathname));
const resources = entries
    .map((file) => {
        const relative = file.pathname.slice(root.pathname.length);
        const namespace = relative.replace('/en/', '/').replace(/\.json$/, '');
        return `        ${JSON.stringify(namespace)}: typeof import(${JSON.stringify('../../locales/' + relative)});`;
    })
    .join('\n');
const target = new URL('../resources/js/types/i18next.d.ts', import.meta.url);
const content = await prettier.format(
    `// Generated by npm run localization:types. Do not edit manually.
import 'i18next';
declare module 'i18next' {
    interface CustomTypeOptions {
        defaultNS: 'global/common';
        enableSelector: false;
        strictKeyChecks: true;
        resources: {
${resources}
        };
    }
}
`,
    { ...(await prettier.resolveConfig(fileURLToPath(target))), filepath: fileURLToPath(target) },
);
if (process.argv.includes('--check')) {
    if (readFileSync(target, 'utf8') !== content) throw new Error('Translation types are stale. Run npm run localization:types.');
} else writeFileSync(target, content);
